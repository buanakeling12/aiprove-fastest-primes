#!/usr/bin/env python3
"""Regenerate pitab.h: pitab[k] = pi(k*1000) for k=0..5000.

Computed with a plain bytearray sieve up to 5,000,000. No network needed.
Run: python3 gen_table.py   (writes pitab.h in the current directory)
"""
import math

N = 5_000_000
s = bytearray(b'\x01') * (N + 1)
s[0:2] = b'\x00\x00'
for i in range(2, int(math.isqrt(N)) + 1):
    if s[i]:
        s[i*i:N+1:i] = b'\x00' * ((N - i*i)//i + 1)

pi = [0] * (N + 1)
c = 0
for i, v in enumerate(s):
    c += v
    pi[i] = c

tab = [pi[k * 1000] for k in range(5001)]
assert tab[0] == 0 and tab[5] == 669 and tab[100] == 9592
assert tab[1000] == 78498 and tab[5000] == 348513

with open('pitab.h', 'w') as f:
    f.write('/* Generated by gen_table.py: pitab[k] = pi(k*1000), k=0..5000. */\n')
    f.write('static const int pitab[] = {\n')
    for j in range(0, len(tab), 12):
        f.write(','.join(str(x) for x in tab[j:j + 12]) + ',\n')
    f.write('};\n')

print('pitab.h written:', len(tab), 'entries; pi(5000000) =', tab[5000])
